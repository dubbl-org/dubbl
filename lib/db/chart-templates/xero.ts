import type { AccountKind, AccountTemplate, ChartTemplate, DefaultTax } from "./types";

/**
 * Xero-style default charts of accounts
 * =====================================
 * The 3-digit charts Xero gives a new organisation in the UK, Australia, New
 * Zealand and the US, plus the "global" chart Xero uses everywhere else. Codes
 * and names follow Xero's own defaults so an accountant (or a migrated Xero
 * file) recognises them instantly: 090 bank, 200 Sales, 310 Cost of Goods Sold,
 * 4xx overheads, 610 Accounts Receivable, 800 Accounts Payable, 820 VAT/GST,
 * 960 Retained Earnings (US: 120 AR, 200 AP, 400 Sales, 6xx expenses).
 *
 * Every account the posting engine needs carries `roles` (the canonical
 * generic code it stands in for), so an invoice still asks for "1200" and lands
 * on 610. Where the engine needs something Xero doesn't ship by default (goods
 * received not invoiced, customer deposits…), `onDemand` places it in the same
 * numbering, created only on first use.
 *
 * One deliberate difference: Xero holds VAT/GST in a single 820 account, but
 * dubbl builds the tax return from ledger movements, so tax reclaimable on
 * purchases gets its own account (821) next to it.
 */

function a(
  code: string,
  name: string,
  type: AccountKind,
  subType: string,
  roles?: string[],
  tax?: DefaultTax,
): AccountTemplate {
  return { code, name, type, subType, ...(roles ? { roles } : {}), ...(tax ? { tax } : {}) };
}

